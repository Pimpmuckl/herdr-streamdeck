import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const sourcePath = resolve(process.env.HERDR_THEME_SOURCE || "../herdr/src/app/state.rs");
const targetPath = resolve("src/herdr-themes.ts");
const source = readFileSync(sourcePath, "utf8");
const themes = [
  ["catppuccin", "catppuccin", "dark", ["catppuccin-mocha"]],
  ["catppuccin-latte", "catppuccin_latte", "light", ["latte", "light"]],
  ["tokyo-night", "tokyo_night", "dark", ["tokyonight"]],
  ["tokyo-night-day", "tokyo_night_day", "light", ["tokyo-day", "tokyonight-day"]],
  ["dracula", "dracula", "dark", []],
  ["nord", "nord", "dark", []],
  ["gruvbox", "gruvbox", "dark", ["gruvbox-dark"]],
  ["gruvbox-light", "gruvbox_light", "light", []],
  ["one-dark", "one_dark", "dark", ["onedark"]],
  ["one-light", "one_light", "light", ["onelight"]],
  ["solarized", "solarized", "dark", ["solarized-dark"]],
  ["solarized-light", "solarized_light", "light", []],
  ["kanagawa", "kanagawa", "dark", []],
  ["kanagawa-lotus", "kanagawa_lotus", "light", ["lotus"]],
  ["rose-pine", "rose_pine", "dark", ["rosepine"]],
  ["rose-pine-dawn", "rose_pine_dawn", "light", ["rosepine-dawn", "dawn"]],
  ["vesper", "vesper", "dark", []]
];

const parsed = Object.fromEntries(themes.map(([name, functionName, appearance]) => {
  const start = source.indexOf(`pub fn ${functionName}()`);
  const end = source.indexOf("\n    pub fn ", start + 1);
  if (start < 0 || end < 0) throw new Error(`Herdr theme not found: ${functionName}`);
  const palette = Object.fromEntries([...source.slice(start, end).matchAll(/(\w+): Color::Rgb\((\d+),\s*(\d+),\s*(\d+)\)/g)]
    .map((match) => [match[1], { r: Number(match[2]), g: Number(match[3]), b: Number(match[4]) }]));
  if (Object.keys(palette).length !== 16) throw new Error(`Herdr theme is incomplete: ${functionName}`);
  return [name, { name, appearance, palette }];
}));

const aliases = Object.fromEntries(themes.flatMap(([name, , , values]) => values.map((alias) => [alias, name])));
const output = `// Generated by scripts/sync-herdr-themes.mjs from Herdr src/app/state.rs.\n`
  + `// Temporary compatibility copy until Herdr exposes its resolved runtime palette.\n\n`
  + `import type { ResolvedThemeSnapshot } from "./model.js";\n\n`
  + `const themes: Record<string, ResolvedThemeSnapshot> = ${JSON.stringify(parsed, null, 2)};\n\n`
  + `const aliases: Record<string, string> = ${JSON.stringify(aliases, null, 2)};\n\n`
  + `export function copiedHerdrTheme(name: string): ResolvedThemeSnapshot | undefined {\n`
  + `  const normalized = name.toLowerCase().replace(/[ _]+/g, "-");\n`
  + `  const theme = themes[aliases[normalized] ?? normalized];\n`
  + `  return theme ? structuredClone(theme) : undefined;\n`
  + `}\n`;

writeFileSync(targetPath, output, "utf8");
console.log(`Copied ${themes.length} Herdr themes to ${targetPath}`);
